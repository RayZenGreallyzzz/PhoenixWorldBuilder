'use strict';
const assert=require('node:assert/strict');
const {skill,power,Catalog,Runtime}=require('../app/src/main/assets/engine/core/phoenix-skills.js');
const fire={name:'Огненный шар',description:'Урон противнику',icon:'🔥',
 type:'damage',basePower:80,growth:25,level:1,maxLevel:5,manaCost:30,
 cooldown:6,range:12,animation:'cast'};
assert.equal(power(fire),80);
assert.equal(power({...fire,level:2}),105);
assert.equal(power({...fire,level:3}),130);
assert.equal(power({...fire,level:5}),180);
assert.throws(()=>skill({...fire,level:6}),/level/);
assert.throws(()=>skill({...fire,description:'x'.repeat(401)}),/description/);
assert.throws(()=>skill({...fire,icon:'<script>'}),/icon/);
assert.throws(()=>skill({...fire,manaCost:-2}),/manaCost/);
const catalog=new Catalog();
catalog.set('player','slot3',fire);
catalog.set('prefab-1','ultimate',{...fire,name:'Медвежий рев',basePower:30});
assert.equal(catalog.get('player','slot3').name,'Огненный шар');
assert.equal(catalog.get('prefab-1','ultimate').name,'Медвежий рев');
const copied=catalog.get('player','slot3');copied.basePower=999;
assert.equal(catalog.get('player','slot3').basePower,80);
const snapshot=JSON.parse(JSON.stringify(catalog.serialize()));
const loaded=new Catalog();loaded.load(snapshot);
assert.deepEqual(loaded.serialize(),snapshot);
assert.throws(()=>loaded.load({version:1,characters:[...snapshot.characters,snapshot.characters[0]]}),/Invalid/);
assert.deepEqual(loaded.serialize(),snapshot,'Failed load must be atomic');
const mana=new Runtime(catalog,'player',100);
assert.equal(mana.status(0).mp,100);
assert.equal(mana.cast('slot4',0).reason,'unassigned');
assert.equal(mana.cast('slot3',1,()=>false).reason,'no-target');
assert.equal(mana.status(1).mp,100,'No target must not spend mana');
const shot=mana.cast('slot3',1,()=>true);
assert.equal(shot.ok,true);
assert.equal(shot.power,80);
assert.equal(shot.mp,70);
assert.equal(mana.cast('slot3',2).reason,'cooldown');
assert.equal(mana.cast('slot3',8,()=>true).mp,40);
assert.equal(mana.cast('slot3',15,()=>true).mp,10);
assert.equal(mana.cast('slot3',25).reason,'mana');
assert.equal(catalog.get('player','slot3').level,1,'PLAY cannot overwrite authored skill level');
assert.deepEqual(new Runtime(catalog,'player').status(0).mp,100);
assert.equal(loaded.remove('prefab-1','ultimate'),true);
assert.equal(loaded.get('prefab-1','ultimate'),null);
console.log('PASS: per-character skills, damage per level, MP, cooldown, JSON and failed-cast safety');
