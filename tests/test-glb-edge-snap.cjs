const assert=require('node:assert/strict'),fs=require('fs'),path=require('path'),vm=require('vm');
const root=path.join(__dirname,'../app/src/main/assets/js');
const THREE=global.THREE=require(path.join(root,'three.min.js'));
global.BuildSnap=require(path.join(root,'build-snap.js'));
vm.runInThisContext(fs.readFileSync(path.join(root,'world.js'),'utf8')+'\nglobal.WorldBuilder=WorldBuilder');
const w=Object.create(WorldBuilder.prototype);
Object.assign(w,{scene:new THREE.Scene(),objects:[],assetCache:new Map(),textures:new Map(),nextId:1,ghost:null,selected:null,moveTarget:null,mode:'playbuild',placement:null,placementCategory:null,placementRotation:0,placementScale:1,smartSnap:true,edgeShift:0,lastSnapResult:null,floorLevel:0,snap:2,currentPaint:'#ada08b',yaw:0});
w.player=new THREE.Group();w.player.position.set(0,.85,0);w.scene.add(w.player);
w.heightAt=()=>0;w.remember=()=>{};w.onChanged=()=>{};w.onSnapChanged=()=>{};w.onSelected=()=>{};
w.highlight={setFromObject(){},visible:false};
w.categoryForKind=id=>id==='glb:custom-floor'?'foundation':id==='glb:custom-wall'?'wall':'prop';
const floor=new THREE.Group(), deck=new THREE.Mesh(new THREE.BoxGeometry(8,.4,5),new THREE.MeshBasicMaterial());
deck.position.set(1.2,.2,-.7);floor.add(deck);floor.position.set(6,1.4,-2);floor.rotation.y=.73;floor.scale.setScalar(1.7);w.scene.add(floor);
w.objects.push({kind:'glb:custom-floor',data:{id:71,pos:floor.position.toArray(),rot:42,scale:1.7},mesh:floor});
const box=BuildSnap.attrBounds(floor);assert(Math.abs(box.max.x-5.2)<.001);
floor.updateMatrixWorld(true);const top=floor.localToWorld(new THREE.Vector3(0,box.max.y,0)).y;
const near=floor.localToWorld(new THREE.Vector3(box.max.x+.12,box.max.y,(box.min.z+box.max.z)/2));
w.player.position.set(near.x,top+.85,near.z);
w.setPlacement('wall','wall');let place=w.solvePlacement(near);
assert(place.snapped&&place.edge,'Must find GLB deck edge');
assert(Math.abs(place.position.y-top)<.005,'Wall bottom must rest on real platform top');
assert.equal(place.reference,71);assert(Math.abs(place.position.x-near.x)<1);
const placed=w.placeAt(near);assert.equal(placed.data.id,1);assert.equal(placed.data.category,'wall');
assert(Math.abs(placed.data.pos[1]-top)<.005,'Saved position must match preview');
const original=w.solvePlacement(near).position.clone();w.shiftAlongEdge(.5);
const shifted=w.solvePlacement(near).position;assert(Math.abs(original.distanceTo(shifted)-.5)<.06,'Fine movement along GLB edge');
w.setPlacement('stairs','stairs');place=w.solvePlacement(near);assert(place.snapped);
const stairBounds=BuildSnap.attrBounds(w.ghost);
assert(Math.abs(place.position.y+stairBounds.max.y-top)<.005,'Last step must reach the deck');
w.setPlacement('wall','wall');w.smartSnap=false;place=w.solvePlacement(near);
assert(!place.snapped&&Math.abs(place.position.x/2-Math.round(place.position.x/2))<.001,'Free placement still uses grid');
console.log('Rotated and scaled GLB decks support wall/stair snapping, fine movement, and saved coordinates');
