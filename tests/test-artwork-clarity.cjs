const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const dir=path.join(__dirname,'../app/src/main/assets/js');
const THREE=global.THREE=require(path.join(dir,'three.min.js'));
vm.runInThisContext(fs.readFileSync(path.join(dir,'world.js'),'utf8')+'\nglobal.WorldBuilder=WorldBuilder');
const world=Object.create(WorldBuilder.prototype);
const renderSizes=[];
world.renderer={capabilities:{getMaxAnisotropy:()=>16,isWebGL2:false},
 shadowMap:{enabled:false},setSize:(x,y)=>renderSizes.push([x,y])};
world.scene=new THREE.Scene();world.sun={castShadow:false};
world.canvas={getBoundingClientRect:()=>({width:800,height:600})};
world.camera={aspect:1,updateProjectionMatrix:()=>{}};
world.textures=new Map();world.assetCache=new Map();
const art=new THREE.Texture({width:2080,height:756});
art.wrapS=art.wrapT=THREE.ClampToEdgeWrapping;
const tiled=new THREE.Texture({width:1024,height:1024});
tiled.wrapS=tiled.wrapT=THREE.RepeatWrapping;
world.textures.set('emblem:painting',art);
world.textures.set('tex:wall-stone',tiled);
const glbMap=new THREE.Texture({width:1024,height:512});
const glb=new THREE.Group();
glb.add(new THREE.Mesh(new THREE.PlaneGeometry(2,2),new THREE.MeshBasicMaterial({map:glbMap})));
world.assetCache.set('glb:wall',glb);
assert.equal(world.setTextureQuality(8),8);
assert.equal(art.anisotropy,8);
assert.equal(art.minFilter,THREE.LinearFilter,'Non-power-of-two art on WebGL1 keeps original pixels');
assert.equal(art.generateMipmaps,false);
assert.equal(tiled.minFilter,THREE.LinearMipmapLinearFilter);
assert.equal(glbMap.anisotropy,8,'Imported GLB materials use the same user-selected quality');
world.renderer.capabilities.isWebGL2=true;
world.setTextureQuality(4);
assert.equal(art.minFilter,THREE.LinearMipmapLinearFilter,'WebGL2 supports native-size mipmaps');
assert.equal(art.generateMipmaps,true);
assert.equal(glbMap.anisotropy,4);
world.setQuality(1.25,false);
assert.equal(world.renderScale,1.25);
assert.deepEqual(renderSizes.at(-1),[1000,750],'Super-resolution draws 125% of CSS viewport');
assert.equal(world.setTextureQuality(999),4,'Bad settings fall back to safe mode');
const index=fs.readFileSync(path.join(dir,'../index.html'),'utf8');
const app=fs.readFileSync(path.join(dir,'app.js'),'utf8');
assert(index.includes('id="textureDetail"')&&index.includes('value="1.25"'));
assert(app.includes("pwb_render_scale")&&app.includes("pwb_texture_detail"),'Quality survives app restart');
assert(app.includes('w.tuneModelTextures(parsed.root)'), 'Imported GLB texture quality is applied');
assert(app.includes('w.tuneTexture(t)'),'PNG and JPEG receive quality filtering');
console.log('Artwork clarity and WebGL1/WebGL2 native resolution settings OK');
