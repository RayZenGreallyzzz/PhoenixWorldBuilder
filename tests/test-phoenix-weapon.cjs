'use strict';
const assert=require('node:assert/strict');
const {Session}=require('../app/src/main/assets/engine/core/phoenix-weapon.js');
const gun=new Session({magazineSize:3,reserveCapacity:5,damage:24,fireInterval:.25,reloadDuration:1.5});
assert.deepEqual(gun.status(),{ammo:3,reserve:5,magazineSize:3,reloading:false,remaining:0,aiming:false,damage:24,range:32});
assert.equal(gun.fire(1).ok,true);
assert.equal(gun.fire(1.01).reason,'cooldown');
assert.equal(gun.fire(1.26).ammo,1);
assert.equal(gun.fire(1.52).ammo,0);
assert.equal(gun.fire(2).reason,'empty');
assert.equal(gun.reload(2).ok,true);
assert.equal(gun.reload(2.1).reason,'reloading');
assert.equal(gun.fire(3).reason,'reloading');
assert.equal(gun.status(3.49).ammo,0);
assert.equal(gun.status(3.51).ammo,3);
assert.equal(gun.status(3.51).reserve,2);
assert.equal(gun.reload(4).reason,'full');
gun.setAim(true);
assert.equal(gun.status(4).aiming,true);
gun.reset();
assert.equal(gun.status(0).ammo,3);
assert.equal(gun.status(0).reserve,5);
assert.equal(gun.status(0).aiming,false);
assert.throws(()=>new Session({magazineSize:-1}),/magazineSize/);
assert.throws(()=>new Session({fireInterval:0}),/fireInterval/);
console.log('PASS: shooter fire-rate, ammo, ADS, reload duration, reserve and respawn reset');
